def next_number(table, col, prefix, width):
    # Invoice numbering must be independent by voucher kind/prefix.
    # In particular, purchase invoice numbers must never affect the SALE sequence.
    if table == 'vouchers' and col == 'voucher_no' and prefix == 'SALE-':
        df = q("SELECT voucher_no AS no FROM vouchers WHERE kind='SALE' AND voucher_no LIKE 'SALE-%'")
        nums = []
        if not df.empty:
            for value in df['no'].astype(str):
                # Accept the normal fixed-width sale sequence only. This deliberately
                # ignores malformed legacy numbers such as SALE-224568 that were
                # generated when purchase numbers accidentally influenced numbering.
                match = re.fullmatch(r'SALE-(\d{4})', value.strip())
                if match:
                    nums.append(int(match.group(1)))
        return f"SALE-{max(nums or [0]) + 1:04d}"
    df=q(f"SELECT {col} AS no FROM {table}")
    nums=[]
    if not df.empty:
        for value in df['no'].astype(str):
            match=re.fullmatch(re.escape(prefix) + r'(\d+)', value.strip())
            if match:
                nums.append(int(match.group(1)))
    return f"{prefix}{max(nums or [0])+1:0{width}d}"
